/* one nibble into the decoder state. Inlined, and the delta built with masks instead of three branches (the same
 * sum: a mask is all ones or none), so a decoding loop keeps pred and idx in registers and the inner loop has one
 * branch, the sign's. The encoder (ima_enc_st) runs the same step, so the two stay in step */
static inline __attribute__((always_inline)) int32_t ima_step(int32_t *pred, int32_t *idx, uint32_t code)
{
    int32_t step = IMA_STEP[*idx], p;
    int32_t vd = (step >> 3) + (step & -(int32_t)((code >> 2) & 1u)) + ((step >> 1) & -(int32_t)((code >> 1) & 1u)) +
                 ((step >> 2) & -(int32_t)(code & 1u));
    p = (code & 8u) ? *pred - vd : *pred + vd;
    *pred = clamp(p, -32768, 32767);
    *idx = IMA_NXT[*idx][code & 7u];
    return *pred;
}

/* n samples of a block (from its stored state) into out: a byte at a time, its low nibble then its high (the
 * same nibbles in the same order as sample by sample) */
static void ima_dec(const uint8_t *data, int32_t pred, int32_t idx, int16_t *out, uint32_t n)
{
    uint32_t i;
    for (i = 0; i + 1u < n; i += 2u) {
        uint32_t byte = data[i >> 1];
        out[i] = (int16_t)ima_step(&pred, &idx, byte & 15u);
        out[i + 1u] = (int16_t)ima_step(&pred, &idx, byte >> 4);
    }
    if (i < n)                                           /* (an odd count: the last low nibble) */
        out[i] = (int16_t)ima_step(&pred, &idx, data[i >> 1] & 15u);
}

/* n samples into a block, from the state (*pred, *idx), which is left at the block's end: the encoder
 * tools/gen_reels.py runs */
static void ima_enc_st(const int16_t *in, int32_t *pst, int32_t *ist, uint8_t *data, uint32_t n)
{
    int32_t pred = *pst, idx = *ist;
    uint32_t i;
    for (i = 0; i < n; i++) {
        int32_t step = IMA_STEP[idx], diff = in[i] - pred, code = 0;
        if (diff < 0) {
            code = 8;
            diff = -diff;
        }
        if (diff >= step) {
            code |= 4;
            diff -= step;
        }
        if (diff >= step >> 1) {
            code |= 2;
            diff -= step >> 1;
        }
        if (diff >= step >> 2)
            code |= 1;
        ima_step(&pred, &idx, (uint32_t)code);
        if (i & 1u)
            data[i >> 1] = (uint8_t)((data[i >> 1] & 15u) | ((uint32_t)code << 4));
        else
            data[i >> 1] = (uint8_t)code;
    }
    *pst = pred;
    *ist = idx;
}

static void ima_enc(const int16_t *in, int32_t pred, int32_t idx, uint8_t *data, uint32_t n)
{
    ima_enc_st(in, &pred, &idx, data, n);
}

/* -------------------------------------------------------------- views --- */
static int uslot_view(uint32_t s, tape_view_t *v);   /* reel.c: a user reel in flash */

/* what a track has chosen: 0 its RAM tape, 1..NREEL a factory reel, then the user reels */
static uint32_t tape_src(uint32_t t) { return (uint32_t)clamp(tp[t].dev[DEV_SRC][TK_REEL], 0, (int32_t)(NREEL + USLOT_N)); }

/* what reel choice s (0: track t's RAM tape, 1..NREEL a factory reel, then the user reels) holds; POLY reads any of
 * them this way, whatever the track's TAPE plays */
static void tape_view_of(uint32_t t, uint32_t s, tape_view_t *v)
{
    v->map = 0;
    if (s > NREEL) {                                   /* a user reel (an empty slot plays nothing) */
        if (!uslot_view(s - NREEL - 1u, v)) {
            v->len = 0;
            v->ram = 0;
            v->data = 0;                               /* (never read: len 0) */
            v->pred = 0;
            v->idx = 0;
            v->peak = 0;
        }
        return;
    }
    if (s) {
        const reel_t *r = &REELS[s - 1u];
        v->data = r->data;
        v->pred = r->pred;
        v->idx = r->idx;
        v->peak = r->peak;
        v->len = r->nblk * TAPE_BLK;
        v->ram = 0;
        return;
    }
    v->data = 0;
    v->pred = 0;
    v->idx = 0;
    v->peak = 0;
    v->map = tape_ctl[t].map;
    v->len = tape_ctl[t].empty ? 0u : tape_ctl[t].nblk * TAPE_BLK;
    if (v->len > tape_ctl[t].trim)                     /* (a take of exact bars: its last block's tail unplayed) */
        v->len -= tape_ctl[t].trim;
    if (v->len > (uint32_t)tape_ctl[t].nch * TAPE_CHS)   /* (a tape its chunks were taken from: what's left) */
        v->len = (uint32_t)tape_ctl[t].nch * TAPE_CHS;
    v->ram = 1;
}

static void tape_view(uint32_t t, tape_view_t *v) { tape_view_of(t, tape_src(t), v); }

/* v hundredths of a percent of len (in two parts: the whole product would pass 32 bits on a long tape) */
static int32_t pct100_of(uint32_t len, int32_t v)
{
    uint32_t u = (uint32_t)clamp(v, 0, 10000);
    return (int32_t)(len / 10000u * u + len % 10000u * u / 10000u);
}

/* the loop window in samples: from STRT, LEN long, both in % of what the track plays; past the tape's end it's
 * trimmed there (so STRT always cuts the start away: before 2026-10-11 the window slid back instead, and at LEN
 * 100 STRT did nothing), at least one block long */
static void tape_window_of(uint32_t t, uint32_t len, int32_t *ls, int32_t *ll)
{
    const int16_t *k = TPD(t, DEV_SRC);
    int32_t s = pct100_of(len, k[TK_STRT]), l = pct100_of(len, k[TK_LEN]);
    if (s + l > (int32_t)len)
        l = (int32_t)len - s;
    if (l < (int32_t)TAPE_BLK)
        l = (int32_t)TAPE_BLK;
    if (s + l > (int32_t)len)                          /* (STRT at the very end: the last block) */
        s = (int32_t)len - l;
    *ls = s < 0 ? 0 : s;
    *ll = l > (int32_t)len ? (int32_t)len : l;
}

/* audio ISR only (the screen calls tape_window_of): the same, its last answer kept per track. TAPE and GRAIN ask
 * every block, and pct100_of's six divides are hardware divides on the target: only when len, STRT or LEN moved */
static struct {
    uint32_t len;
    int16_t strt, lnk;
    int32_t ls, ll;
} tape_win[NTRK];

static void tape_window(uint32_t t, uint32_t len, int32_t *ls, int32_t *ll)
{
    const int16_t *k = TPD(t, DEV_SRC);
    t %= NTRK;
    if (tape_win[t].len != len || tape_win[t].strt != k[TK_STRT] || tape_win[t].lnk != k[TK_LEN] || !len) {
        tape_window_of(t, len, &tape_win[t].ls, &tape_win[t].ll);
        tape_win[t].len = len;
        tape_win[t].strt = k[TK_STRT];
        tape_win[t].lnk = k[TK_LEN];
    }
    *ls = tape_win[t].ls;
    *ll = tape_win[t].ll;
}

/* SYNC's bars (0: off): OFF 1 2 4 8 16 */
static uint32_t tape_sync_bars(uint32_t t)
{
    int32_t s = clamp(tp[t].dev[DEV_SRC][TK_SYNC], 0, 5);
    return s ? 1u << (s - 1) : 0u;
}

/* SYNC: the beat's place in the loop's per beats now, Q16 of the loop */
static uint32_t tape_sync_clock(uint32_t per) { return (mclk.beat % (per << 16)) / per; }

/* SYNC: where the head belongs in the loop now, Q16: ROTATE's start and where a slice key moved it, then the beat's
 * place forward (backwards: back from them, so PLAY starts it just before ROTATE's start, as tape_rot does) */
static uint32_t tape_sync_frac(uint32_t t, uint32_t per, int rev)
{
    uint32_t r = (uint32_t)TPD(t, DEV_SRC)[TK_ROTA] * 65536u / 100u + tape_rt[t].soff, c = tape_sync_clock(per);
    return (rev ? r - c : r + c) & 0xFFFFu;
}

/* the head's step per output sample, Q12 of a tape sample: 0.5 at 100 % (22.05 kHz under 44.1 kHz); SPD
 * -200..200 %, REV turns it round, HALF halves it */
static int32_t tape_inc(uint32_t t)
{
    const int16_t *k = TPD(t, DEV_SRC);
    int32_t inc = 2048 * k[TK_SPD] / 100;
    if (k[TK_REV])
        inc = -inc;
    return k[TK_HALF] ? inc / 2 : inc;
}

/* sample i of the view through reader r (silence outside it) */
static int32_t tape_at(const tape_view_t *v, tape_rd_t *r, int32_t i)
{
    uint32_t blk, o;
    if (i < 0 || (uint32_t)i >= v->len)
        return 0;
    blk = (uint32_t)i / TAPE_BLK;
    o = (uint32_t)i % TAPE_BLK;
    if (!r->ok || r->blk != blk) {
        ima_dec(tv_data(v, blk), tv_pred(v, blk), tv_idx(v, blk), r->s, TAPE_BLK);
        if ((blk + 1u) * TAPE_BLK < v->len) {          /* the next block's first sample */
            int32_t p = tv_pred(v, blk + 1u), x = tv_idx(v, blk + 1u);
            r->s[TAPE_BLK] = (int16_t)ima_step(&p, &x, tv_data(v, blk + 1u)[0] & 15u);
        } else {
            r->s[TAPE_BLK] = r->s[TAPE_BLK - 1u];
        }
        r->blk = (uint16_t)blk;
        r->ok = 1;
    }
    return r->s[o];
}

/* the view at head position pos (Q12), interpolated */
static int32_t tape_read(const tape_view_t *v, tape_rd_t *r, int32_t pos)
{
    int32_t i = pos >> 12, f = pos & 4095, a = tape_at(v, r, i), b;
    if (i < 0 || (uint32_t)i >= v->len)
        return 0;
    b = r->s[((uint32_t)i % TAPE_BLK) + 1u];
    return a + (((b - a) * f) >> 12);
}

/* ------------------------------------------------------------- writer --- */
/* a block's decoder state fitted to its sound: its first sample and the step that suits its first move (an encoder
 * that starts from some other block's state takes a while to catch up: a click a block) */
static void ima_fit(const int16_t *s, int16_t *pred, uint8_t *idx)
{
    int32_t d = s[1] - s[0], id = 0;
    d = d < 0 ? -d : d;
    while (id < 88 && IMA_STEP[id] < d)
        id++;
    *pred = s[0];
    *idx = (uint8_t)id;
}

/* a block's peak, as the screen keeps it */
static uint8_t ima_peak(const int16_t *s, uint32_t n)
{
    uint32_t i;
    int32_t pk = 0;
    for (i = 0; i < n; i++) {
        int32_t a = s[i] < 0 ? -s[i] : s[i];
        if (a > pk)
            pk = a;
    }
    return (uint8_t)(pk >> 7 > 255 ? 255 : pk >> 7);
}

static void tape_commit(uint32_t t)
{
    tape_rt_t *rt = &tape_rt[t];
    uint32_t b = rt->wblk;
    mem_chunk_t *c;
    if (!rt->wstaged)
        return;
    rt->wstaged = 0;
    if (tape_ctl[t].empty || b / MEM_CB >= tape_ctl[t].nch || rt->wgen != tape_ctl[t].gen)
        return;                                        /* cleared meanwhile, its chunk taken, another tape: drop it */
    c = tape_chunk(t, b);
    ima_fit(rt->stage, &c->pred[b % MEM_CB], &c->idx[b % MEM_CB]);
    ima_enc(rt->stage, c->pred[b % MEM_CB], c->idx[b % MEM_CB], c->data[b % MEM_CB], TAPE_BLK);
    c->peak[b % MEM_CB] = ima_peak(rt->stage, TAPE_BLK);
    tape_ver[t]++;
    if (rt->a.blk == b)                                /* readers decode the new block from now on */
        rt->a.ok = 0;
    if (rt->b.blk == b)
        rt->b.ok = 0;
}

/* sample i of the RAM tape becomes old x keep % + in (in: already scaled by its share) */
/* DUB (-100..100) as the old sound's and the new sound's shares, in %: the S-4's SOS, a Morphagene's SOS. 0 is
 * sound on sound (both whole); toward +100 the input fades and the loop stays (+100: REC changes nothing); toward
 * -100 the loop fades on each pass under the input (-100: the input replaces it) */
static void tape_dub(int32_t dub, int32_t *keep, int32_t *in)
{
    *keep = dub >= 0 ? 100 : 100 + dub;
    *in = dub <= 0 ? 100 : 100 - dub;
}

static void tape_write(uint32_t t, int32_t i, int32_t in, int32_t keep)
{
    tape_rt_t *rt = &tape_rt[t];
    uint32_t b = (uint32_t)i / TAPE_BLK;
    if (!rt->wstaged || rt->wblk != b) {
        mem_chunk_t *c = tape_chunk(t, b);
        tape_commit(t);
        ima_dec(c->data[b % MEM_CB], c->pred[b % MEM_CB], c->idx[b % MEM_CB], rt->stage, TAPE_BLK);
        rt->wblk = (uint16_t)b;
        rt->wgen = tape_ctl[t].gen;
        rt->wstaged = 1;
    }
    rt->stage[(uint32_t)i % TAPE_BLK] = (int16_t)clamp(rt->stage[(uint32_t)i % TAPE_BLK] * keep / 100 + in, -32767, 32767);
}

/* ------------------------------------------------------------ the head --- */
/* jump the head to pos, the old head fading out over the fade (FADE, or at least TAPE_DECLICK) */
static void tape_jump(uint32_t t, int32_t pos)
{
    tape_rt_t *rt = &tape_rt[t];
    int32_t fl = TPD(t, DEV_SRC)[TK_FADE] * 441 / 10;   /* ms -> output samples */
    rt->xpos = rt->pos;
    rt->b.ok = 0;
    rt->xflen = rt->xf = fl > TAPE_DECLICK ? fl : TAPE_DECLICK;
    rt->pos = pos;
}

/* where in the loop window [ls, ls + ll) the head sits at its offset o from ROTATE's start (wrapped) */
static int32_t tape_rot(uint32_t t, int32_t ls, int32_t ll, int32_t o)
{
    int32_t r = (ll * TPD(t, DEV_SRC)[TK_ROTA] / 100 + o) % ll;
    return ls + (r < 0 ? r + ll : r);
}

/* white key k: play from slice k of the loop (16 slices); stopped, play just that slice (backwards from its end
 * when the tape runs in reverse) */
static void tape_slice(uint32_t t, uint32_t k, int32_t ls, int32_t ll, int32_t inc)
{
    tape_rt_t *rt = &tape_rt[t];
    int32_t o0 = ll * (int32_t)k / 16, o1 = ll * ((int32_t)k + 1) / 16;   /* (counted from ROTATE's start) */
    tape_jump(t, (inc < 0 ? tape_rot(t, ls, ll, o1 - 1) : tape_rot(t, ls, ll, o0)) << 12);
    if (!sys.playing) {
        rt->running = 1;
        rt->stop_left = (o1 - o0) << 12;              /* (a slice may run over the seam: its length, not its end) */
    }
}

/* a stage's step a block (Q15 of the whole swing), from its time knob (TIME_MS_X10: 0.1 ms units); a block is
 * 32 samples, 0.726 ms. (A divide a block, not a sample) */
static int32_t tape_env_step(int32_t v)
{
    uint32_t st = 237756u / (uint32_t)(TIME_MS_X10[v & 127] | 1u);
    return st > 32767u ? 32767 : st ? (int32_t)st : 1;
}

/* the slice envelope, a block on: its level at this block's end. Stopped, a key's slice goes ATK DEC SUS while that
 * key is held, then REL, and the head stops when it's silent; playing, a key's jump fades in over ATK and the loop
 * runs as it is (TE_IDLE: unity) */
static int32_t tape_env(tape_rt_t *rt, const int16_t *p, uint32_t keys, uint32_t playing)
{
    int32_t sus = clamp(p[TK_SUS], 0, 100) * 32767 / 100;
    int gate = (int)((keys >> rt->ekey) & 1u);
    switch (rt->est) {
    case TE_JUMP:
    case TE_ATK:
        rt->env += tape_env_step(p[TK_ATK]);
        if (rt->env >= 32767) {
            rt->env = 32767;
            rt->est = rt->est == TE_JUMP ? TE_IDLE : TE_DEC;
        }
        break;
    case TE_DEC:
        rt->env -= tape_env_step(p[TK_DEC]);
        if (rt->env <= sus) {
            rt->env = sus;
            rt->est = TE_SUS;
        }
        break;
    case TE_SUS:
        rt->env = sus;
        break;
    case TE_REL:
        rt->env -= tape_env_step(p[TK_REL]);
        if (rt->env <= 0) {
            rt->env = 0;
            rt->est = TE_IDLE;
            if (!playing)
                rt->running = 0;                       /* (released and silent: the slice is over) */
        }
        break;
    default:
        rt->env = playing || rt->running ? 32767 : rt->env;
        break;
    }
    if (!gate && (rt->est == TE_ATK || rt->est == TE_DEC || rt->est == TE_SUS))
        rt->est = TE_REL;                              /* (let go: the release, from where it is) */
    return rt->env;
}

/* audio ISR: n output samples of track t (mono Q15, before level) into out; keys: the white keys held on this
 * track; rec_in: what REC records (n samples), 0 when not recording */
static void tape_block(uint32_t t, uint32_t keys, const int32_t *rec_in, int32_t *out, uint32_t n)
{
    tape_rt_t *rt = &tape_rt[t];
    tape_ctl_t *c = &tape_ctl[t];
    tape_view_t v;
    int32_t ls, ll, inc = tape_inc(t), i, keep, inl, gain = db_q10(TPD(t, DEV_SRC)[TK_GAIN]), wlen, xk, e0, e1;
    uint32_t k, press = keys & ~rt->keys_prev, playing = sys.playing;
    int rec = rec_in && c->rec_ok && tape_src(t) == 0u, grow;
    uint32_t bar = mclk.beat >> 18;                    /* (4 beats a bar) */
    if (!rec || !sys.rec_bars) {                       /* a take of set bars: armed, it waits for a downbeat (PLAY,
                                                         * or the next bar when armed while playing), runs exactly
                                                         * that long, then stops recording */
        rt->rbar = TB_IDLE;
    } else {
        if (rt->rbar == TB_IDLE)
            rt->rbar = TB_WAIT;
        if (rt->rbar == TB_WAIT && playing && (mclk.started || bar != rt->bar)) {
            rt->rbar = TB_REC;
            rt->rec_left = (int32_t)sys.rec_bars * (int32_t)(10584000u / clamp(sys.bpm, 40, 240));   /* (4 x 60 x
                                                         * 44,100 a bar at 1 BPM) */
        }
        if (rt->rbar == TB_REC && !playing)            /* stopped in the middle: the take is what it has */
            rt->rbar = TB_DONE;
        if (rt->rbar != TB_REC)
            rec = 0;
    }
    rt->bar = bar;
    if (c->grow && !rec && rt->rbar != TB_WAIT) {      /* REC let go of a growing tape: its length is what it has */
        c->grow = 0;
        rt->grew = 0;
    }
    grow = c->grow;
    tape_view(t, &v);
    if (grow) {                                        /* growing: forward from the start, no seam until it's full */
        wlen = (int32_t)c->nch * (int32_t)TAPE_CHS;
        ls = 0;
        ll = wlen;
        inc = inc < 0 ? -inc : inc;
        if (rt->rbar == TB_WAIT) {                     /* (waiting for the downbeat: the head parked at the start) */
            rt->running = 0;
            rt->pos = 0;
            rt->grew = 0;
        } else if (!rt->grew && playing) {
            rt->grew = 1;
            rt->pos = 0;
            rt->xf = 0;
            rt->wlast = -1;
            rt->running = 1;
            rt->stop_left = 0;
            rt->was_playing = 1;
        }
    } else {
        wlen = (int32_t)v.len;
        tape_window(t, v.len ? v.len : TAPE_LEN, &ls, &ll);
        int32_t hp = rt->pos >> 12, tol = ll / 16;     /* (a head just short of the window's start, as STRT moves
                                                         * past it, plays on into it: no jump; backwards, past its
                                                         * end the same) */
        if (v.len && rt->running && (inc >= 0 ? hp < ls - tol || hp >= ls + ll : hp < ls || hp >= ls + ll + tol)) {
            int32_t o = ((rt->pos >> 12) - ls) % ll;  /* (the tape got shorter under the head: back inside) */
            tape_jump(t, (ls + (o < 0 ? o + ll : o)) << 12);
            rt->wlast = -1;
        }
        if (tp[t].dev[DEV_SRC][TK_ROTA] != rt->rota) { /* ROTATE turned: the loop turns under the head (it plays
                                                         * on from where the new rotation puts it: the same moment
                                                         * of the bar now hears another part of the tape). The knob,
                                                         * not its modulation: a modulated ROTA moves where PLAY and
                                                         * the slices start (and SYNC's lock), as it always did */
            int32_t d = tp[t].dev[DEV_SRC][TK_ROTA] - rt->rota, o;
            rt->rota = tp[t].dev[DEV_SRC][TK_ROTA];
            if (v.len && rt->running && playing && rt->stop_left == 0) {
                o = ((rt->pos >> 12) - ls + ll * d / 100) % ll;
                tape_jump(t, ((ls + (o < 0 ? o + ll : o)) << 12) | (rt->pos & 4095));
                rt->wlast = -1;
            }
        }
    }
    rt->keys_prev = keys;
    tape_dub(grow ? -100 : TPD(t, DEV_SRC)[TK_DUB], &keep, &inl);   /* (a blank tape: nothing to keep) */
    gain = gain * inl / 100;
    if (!inl)
        rec = 0;                                       /* DUB +100: nothing comes in, so nothing is re-encoded */
    if (playing != rt->was_playing) {                  /* the transport: all heads from the loop's start (ROTATE's) */
        rt->was_playing = (uint8_t)playing;
        rt->est = TE_IDLE;                             /* (the transport: the loop as it is) */
        rt->env = 32767;
        if (playing) {
            mod_seam |= (uint8_t)(1u << t);            /* (the loop starts: an ADSR's one-shot, mod.c) */
            rt->soff = 0;                              /* (SYNC: the loop starts with the bar) */
            rt->pos = (grow ? 0 : tape_rot(t, ls, ll, inc < 0 ? -1 : 0)) << 12;
            rt->xf = 0;
            rt->running = 1;
            rt->stop_left = 0;
        } else {
            rt->running = 0;                           /* (the ramp fades it) */
        }
    }
    for (k = 0; press && !grow && k < NWHITE; k++)       /* a new key: its slice (the lowest, one per block) */
        if ((press >> k) & 1u) {
            tape_slice(t, k, ls, ll, inc);
            rt->est = playing ? TE_JUMP : TE_ATK;      /* (its envelope, from silence) */
            rt->ekey = (uint8_t)k;
            rt->env = 0;
            if (tape_sync_bars(t) && playing) {        /* (SYNC: the loop goes on from the slice, against the beat;
                                                         * backwards from the slice's end) */
                uint32_t c = tape_sync_clock(tape_sync_bars(t) * 4u);
                rt->soff = (uint16_t)(inc < 0 ? (k + 1u) * 4096u + c : k * 4096u - c);
            }
            break;
        }
    if (tape_sync_bars(t) && !grow && !rec && v.len) {   /* SYNC: the loop lasts its bars at the tempo. The speed
                                                         * for that, and a soft lock to the beat: the error to where
                                                         * the beat says the head is pulls the speed by at most 1/64
                                                         * (a quarter tone), so it never jumps; a large one (a new
                                                         * tempo, the transport) jumps there, crossfaded */
        uint32_t per = tape_sync_bars(t) * 4u, out = per * (2646000u / (uint32_t)clamp(sys.bpm, 40, 240));
        int32_t s = (int32_t)(((uint32_t)ll << 12) / out);
        inc = inc < 0 ? -s : s;
        if (playing && rt->running && rt->stop_left == 0) {
            uint32_t f = tape_sync_frac(t, per, inc < 0);
            int32_t o = (int32_t)(((uint32_t)ll >> 16) * f + ((((uint32_t)ll & 0xFFFFu) * f) >> 16));
            int32_t p = inc < 0 ? (o ? ls + o - 1 : ls + ll - 1) : ls + o, d = p - (rt->pos >> 12);
            if (d > ll / 2)
                d -= ll;
            else if (d < -ll / 2)
                d += ll;
            if (d > ll / 8 || d < -ll / 8) {
                tape_jump(t, p << 12);
                rt->wlast = -1;
            } else {
                inc += clamp(d * 2, -(s >> 6), s >> 6);   /* (the error over ~2,000 samples) */
            }
        }
    }
    if (grow) {                                        /* (a growing tape: as it is) */
        rt->est = TE_IDLE;
        rt->env = 32767;
    }
    e0 = rt->env;                                      /* (the last block's end; a new slice's: 0) */
    e1 = tape_env(rt, TPD(t, DEV_SRC), keys, playing);
    if (!rec && rt->wstaged)
        tape_commit(t);                                /* REC let go: the last block */
    xk = 0;
    for (i = 0; i < (int32_t)n; i++) {
        int32_t s = 0, tgt = rt->running ? 32767 : 0;
        rt->amp += rt->amp < tgt ? 372 : rt->amp > tgt ? -372 : 0;   /* ~2 ms either way */
        rt->amp = clamp(rt->amp, 0, 32767);
        if (rt->amp) {
            s = tape_read(&v, &rt->a, rt->pos);
            if (rt->xf > 0) {                          /* the old head fading out (its share xf / xflen, Q14: a
                                                         * multiply, xk worked out once a block, not a divide a sample) */
                int32_t o = tape_read(&v, &rt->b, rt->xpos);
                if (!xk)
                    xk = (int32_t)((1u << 28) / (uint32_t)(rt->xflen > 0 ? rt->xflen : 1));
                s += ((o - s) * ((rt->xf * xk) >> 14)) >> 14;
                rt->xpos += inc;
                rt->xf--;
            }
            s = (s * rt->amp) >> 15;
            if (e0 != 32767 || e1 != 32767)            /* the slice envelope, ramped across the block */
                s = (s * (e0 + ((e1 - e0) * i >> CTL_LOG2))) >> 15;
        }
        out[i] = s;
        if (!rt->running)
            continue;
        if (rec && playing) {                          /* REC: every tape sample the head passes */
            int32_t a = rt->pos >> 12, w = rt->wlast < 0 ? a : rt->wlast, in = rec_in[i] * gain >> 10;
            if (w != a) {
                int32_t d = a > w ? 1 : -1;
                for (w += d; w != a + d; w += d)
                    if (w >= 0 && w < wlen)
                        tape_write(t, w, in, keep);
            } else if (rt->wlast < 0 && a >= 0 && a < wlen) {
                tape_write(t, a, in, keep);
            }
            rt->wlast = a;
            if (grow && a >= 0 && a < wlen && (uint32_t)a / TAPE_BLK >= c->nblk)
                c->nblk = (uint16_t)((uint32_t)a / TAPE_BLK + 1u);   /* the tape is as long as the head has gone */
            if (rt->rbar == TB_REC && --rt->rec_left <= 0) {   /* the bars are in: the take ends here, exactly */
                rt->rbar = TB_DONE;
                rec = 0;
                if (grow) {                            /* a blank tape: as long as the bars, to the sample */
                    rt->rec_full = 1;
                    int32_t len = (rt->pos + inc) >> 12;
                    c->nblk = (uint16_t)((len + (int32_t)TAPE_BLK - 1) / (int32_t)TAPE_BLK);
                    c->trim = (uint8_t)((int32_t)c->nblk * (int32_t)TAPE_BLK - len);
                    c->grow = 0;
                    rt->grew = 0;
                    grow = 0;
                    ls = 0;                            /* (it loops from here: the head wraps at the take's end) */
                    ll = len;
                }
            }
        } else {
            rt->wlast = -1;
        }
        rt->pos += inc;
        if (rt->stop_left > 0 && (rt->stop_left -= inc < 0 ? -inc : inc) <= 0) {
            rt->running = 0;                           /* a slice played while stopped: its end */
            rt->stop_left = 0;
        } else if (inc >= 0 && rt->pos >= (ls + ll) << 12) {
            if (grow) {                                /* every chunk filled: it stops growing and loops */
                c->grow = 0;
                rt->grew = 0;
                grow = 0;
                c->nblk = (uint16_t)((uint32_t)wlen / TAPE_BLK);
            }
            tape_jump(t, rt->pos - (ll << 12));        /* the seam, crossfaded */
            rt->wlast = -1;
            mod_seam |= (uint8_t)(1u << t);
        } else if (inc < 0 && rt->pos < ls << 12) {
            tape_jump(t, rt->pos + (ll << 12));
            rt->wlast = -1;
            mod_seam |= (uint8_t)(1u << t);
        }
    }
}

/* ----------------------------------------------------- main loop side --- */
static void tape_init(void)
{
    uint32_t t;
    mem_init();
    tape_bars_done = 0;
    for (t = 0; t < NTRK; t++) {
        tape_rt[t].wlast = -1;
        tape_rt[t].stop_left = 0;
        tape_rt[t].est = TE_IDLE;
        tape_rt[t].env = 32767;
        tape_ctl[t].nblk = 0;
        tape_ctl[t].nch = 0;
        tape_ctl[t].grow = 0;
        tape_ctl[t].empty = 0;
    }
}

/* track t's tape gives up its last chunk (the list shortened first, then the chunk freed: mem.c) */
static void tape_drop_chunk(uint32_t t)
{
    tape_ctl_t *c = &tape_ctl[t];
    uint32_t n = c->nch;
    if (!n)
        return;
    if (c->nblk > (n - 1u) * MEM_CB) {
        c->nblk = (uint16_t)((n - 1u) * MEM_CB);
        c->trim = 0;
    }
    c->nch = (uint8_t)(n - 1u);
    mem_free(c->map[n - 1u]);
    if (tape_undo.valid && tape_undo.trk == t)       /* (a cleared take that lost a chunk can't come back) */
        tape_undo.valid = 0;
    tape_ver[t]++;
}

/* every chunk of track t's tape back to the pool */
static void tape_free(uint32_t t)
{
    tape_ctl[t].gen++;                                 /* (a block the ISR staged on it is dropped, not committed) */
    tape_ctl[t].nblk = 0;
    while (tape_ctl[t].nch)
        tape_drop_chunk(t);
}

/* a parked track: TRACKS is set below it, so it's switched off */
static int tape_parked(uint32_t t) { return sys.ntrk && t >= sys.ntrk; }

/* Nothing free: take a chunk off the end of a tape, in this order, never from track except or a tape that's
 * growing: a cleared tape, a parked track's tape (the longest), then, when `active` allows, the longest tape of all.
 * Returns 1 when a chunk came free. */
static int tape_steal(uint32_t except, int active)
{
    uint32_t t, best = NTRK, bn = 0, pass;
    for (pass = 0; pass < 3u; pass++) {
        if (pass == 2u && !active)
            break;
        for (t = 0; t < NTRK; t++) {
            tape_ctl_t *c = &tape_ctl[t];
            if (t == except || c->grow || !c->nch)
                continue;
            if (pass == 0u && !c->empty)
                continue;
            if (pass == 1u && !tape_parked(t))
                continue;
            if (c->nch > bn) {
                bn = c->nch;
                best = t;
            }
        }
        if (best < NTRK) {
            tape_drop_chunk(best);
            return 1;
        }
    }
    return 0;
}

/* a chunk for owner o (taking one when none is free; active: as tape_steal), or -1 */
static int32_t tape_alloc(uint32_t o, uint32_t except, int active)
{
    int32_t c = mem_alloc(o);
    if (c < 0 && tape_steal(except, active))
        c = mem_alloc(o);
    return c;
}

/* track t's tape holds at least nch chunks (stealing as tape_steal allows); returns how many it holds */
static uint32_t tape_reserve(uint32_t t, uint32_t nch, int active)
{
    tape_ctl_t *c = &tape_ctl[t];
    while (c->nch < nch && c->nch < TAPE_MAXCH) {
        int32_t k = tape_alloc(MEM_TAPE + t, t, active);
        if (k < 0)
            break;
        c->map[c->nch] = (uint8_t)k;
        RING_PUBLISH();                                /* (the entry before the count that hands it to the ISR) */
        c->nch++;
    }
    return c->nch;
}

/* REC armed on track t: make its RAM tape ready to be written. A reel is copied in (REEL turns to TAPE), taking the
 * chunks it needs; a cleared or unused tape starts blank and grows as it records. Returns 1 ready; 0, leaving REC
 * off, when a reel would overwrite a RAM tape that holds a take (clear it, or set REEL to TAPE, first); -1 when
 * there's no memory to record into. */
static int tape_prepare(uint32_t t)
{
    tape_ctl_t *c = &tape_ctl[t];
    uint32_t s = tape_src(t), b, nb;
    if (c->rec_ok)
        return 1;
    if (s) {                                           /* a reel (factory or yours): copied onto the tape */
        tape_view_t v;
        if (c->nblk && !c->empty)
            return 0;
        tape_view(t, &v);
        nb = (v.len + TAPE_BLK - 1u) / TAPE_BLK;       /* (a take of exact bars: its last block too, trimmed) */
        if (!nb)                                       /* an empty user slot: record onto a blank tape */
            goto blank;
        c->empty = 1;                                  /* (silent while it's copied) */
        tape_free(t);
        if (tape_reserve(t, (nb + MEM_CB - 1u) / MEM_CB, 1) * MEM_CB < nb)
            nb = (uint32_t)c->nch * MEM_CB;            /* (not all of it fits: as much as does) */
        if (!nb)
            return -1;
        for (b = 0; b < nb; b++) {
            mem_chunk_t *m = tape_chunk(t, b);
            memcpy(m->data[b % MEM_CB], tv_data(&v, b), TAPE_BLK / 2u);
            m->pred[b % MEM_CB] = (int16_t)tv_pred(&v, b);
            m->idx[b % MEM_CB] = (uint8_t)tv_idx(&v, b);
            m->peak[b % MEM_CB] = (uint8_t)tv_peak(&v, b);
        }
        c->trim = (uint8_t)(nb * TAPE_BLK > v.len ? nb * TAPE_BLK - v.len : 0u);
        c->nblk = (uint16_t)nb;
        c->empty = 0;
        tp[t].dev[DEV_SRC][TK_REEL] = 0;               /* the track plays its tape (the same sound) */
    } else if (c->empty || !c->nblk) {
    blank:
        c->empty = 1;
        tape_free(t);
        if (tape_reserve(t, 2u, 1) == 0u)              /* (two chunks ready: the main loop adds the rest in time) */
            return -1;
        tp[t].dev[DEV_SRC][TK_REEL] = 0;
        c->nblk = 0;
        c->trim = 0;
        tape_rt[t].grew = 0;
        c->grow = 1;
        c->empty = 0;
    }
    if (tape_undo.valid && tape_undo.trk == t)         /* the cleared take is gone now */
        tape_undo.valid = 0;
    RING_PUBLISH();
    c->rec_ok = 1;
    tape_ver[t]++;
    return 1;
}

static void tape_unprepare(uint32_t t) { tape_ctl[t].rec_ok = 0; }

/* main loop, every pass: a growing tape keeps a chunk ready ahead of its head; one done growing gives back the chunks
 * past its end */
static void tape_poll(void)
{
    uint32_t t;
    for (t = 0; t < NTRK; t++) {
        tape_ctl_t *c = &tape_ctl[t];
        if (tape_rt[t].rbar == TB_DONE && ((sys.rec >> t) & 1u)) {   /* a take of set bars is in: REC lets go */
            sys.rec &= (uint8_t)~(1u << t);
            tape_unprepare(t);
            tape_bars_done |= (uint8_t)(1u << t);
            if (tape_rt[t].rec_full) {                 /* (all its bars, on a blank tape: SYNC to them, so it keeps
                                                         * to the bars when the tempo moves) */
                uint32_t s = 1u, b = sys.rec_bars;
                while (b > 1u) {
                    b >>= 1;
                    s++;
                }
                tp[t].dev[DEV_SRC][TK_SYNC] = (int16_t)(sys.rec_bars ? s : 0u);
                tape_rt[t].rec_full = 0;
            }
        }
        if (c->grow) {
            if ((uint32_t)c->nch * MEM_CB < c->nblk + 2u * MEM_CB)   /* (two chunks, 372 ms, ready ahead) */
                tape_reserve(t, c->nch + 1u, 1);
        } else if (!c->rec_ok && !c->empty) {
            while (c->nch && (uint32_t)(c->nch - 1u) * MEM_CB >= c->nblk)
                tape_drop_chunk(t);
        }
    }
}

/* main loop: track t's tape becomes the n chunks of map (owned by someone else until now: a WAV that arrived over
 * USB, a take from the USB record mode), nblk blocks of sound; the old tape's chunks go back to the pool, the track
 * plays its tape (REEL TAPE), REC on it lets go and a cleared take's undo goes. Silent while it swaps. */
static void tape_replace(uint32_t t, const uint8_t *map, uint32_t n, uint32_t nblk)
{
    tape_ctl_t *c = &tape_ctl[t];
    uint32_t k;
    c->rec_ok = 0;
    c->grow = 0;
    c->empty = 1;                                       /* (silent while it's swapped) */
    tape_free(t);
    for (k = 0; k < n; k++) {
        c->map[k] = map[k];
        mem_give(map[k], MEM_TAPE + t);
    }
    RING_PUBLISH();
    c->nch = (uint8_t)n;
    c->nblk = (uint16_t)nblk;
    c->trim = 0;
    tp[t].dev[DEV_SRC][TK_REEL] = 0;
    sys.rec &= (uint8_t)~(1u << t);
    if (tape_undo.valid && tape_undo.trk == t)
        tape_undo.valid = 0;
    RING_PUBLISH();
    c->empty = 0;
    tape_ver[t]++;
}

/* the POLY key held: clear what track t plays (a reel: the track goes back to its tape, cleared) */
static void tape_clear(uint32_t t)
{
    tape_ctl[t].rec_ok = 0;
    tape_ctl[t].grow = 0;
    tape_undo.valid = 1;
    tape_undo.trk = (uint8_t)t;
    tape_undo.src = (uint8_t)tape_src(t);
    tape_undo.empty = tape_ctl[t].empty;
    tp[t].dev[DEV_SRC][TK_REEL] = 0;
    tape_ctl[t].empty = 1;
    tape_ver[t]++;
}

/* SAVE held: undo the last clear, while nothing has been recorded over it; returns the track, or -1 */
static int32_t tape_undo_clear(void)
{
    uint32_t t = tape_undo.trk;
    if (!tape_undo.valid)
        return -1;
    tape_undo.valid = 0;
    tape_ctl[t].empty = tape_undo.empty;
    tp[t].dev[DEV_SRC][TK_REEL] = tape_undo.src;
    tape_ver[t]++;
    return (int32_t)t;
}

/* for the screen: the peak (0..1000) of what track t plays at pos (0..1000 of it), and where its head is (0..1000;
 * -1 when it isn't running) */
static int32_t tape_peak_at(uint32_t t, int32_t pos)
{
    tape_view_t v;
    uint32_t b;
    tape_view(t, &v);
    if (!v.len)
        return 0;
    b = (uint32_t)clamp(pos, 0, 999) * (v.len / TAPE_BLK) / 1000u;
    return (int32_t)tv_peak(&v, b) * 1000 / 255;
}

static int32_t tape_head(uint32_t t)
{
    tape_view_t v;
    tape_view(t, &v);
    if (!tape_rt[t].running || !v.len)
        return -1;
    return clamp((tape_rt[t].pos >> 12) * 1000 / (int32_t)v.len, 0, 1000);
}

/* the length of what track t plays, in ms (0: nothing) */
static int32_t tape_ms(uint32_t t)
{
    tape_view_t v;
    tape_view(t, &v);
    return (int32_t)(v.len * 10u / (TAPE_SR / 100u));
}

/* the name of what track t plays: a reel's, TAPE, or EMPTY */
static const char *tape_name_of(uint32_t t, uint32_t s)   /* reel choice s, as the screen names it */
{
    if (s > NREEL)
        return uslot_name[s - NREEL - 1u];
    return s ? REELS[s - 1u].name : tape_ctl[t].empty || !tape_ctl[t].nblk ? "EMPTY" : "TAPE";
}

static const char *tape_name(uint32_t t) { return tape_name_of(t, tape_src(t)); }
